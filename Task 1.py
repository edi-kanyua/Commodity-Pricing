# Class that uses historical price data to predict gas prices and extrapolate future prices.

class NatGasPriceModel:
    """
    Estimates natural gas purchase price for any date.

    - For dates within the historical range: linear interpolation between
      known monthly data points (most accurate, grounded in real data).
    - For dates beyond the historical range (future, up to ~1 year out):
      extrapolates using a fitted linear trend + additive monthly seasonal
      index. Returns a point estimate plus a naive confidence interval that
      widens with distance into the future.
    """

    def __init__(self, data, model_params=None):
        self.df = data
        self.first_date = df['Dates'].min()
        self.last_date = df['Dates'].max()

        # Numeric time axis (days since epoch) for interpolation
        self._x_known = df['Dates'].map(pd.Timestamp.toordinal).values
        self._y_known = df['Prices'].values

        if model_params:
            params = model_params
            self.t0 = pd.Timestamp(params['t0'])
            self.slope = params['slope']
            self.intercept = params['intercept']
            self.seasonal_index = {int(k): v for k, v in params['seasonal_index'].items()}
            self.residual_std = params['residual_std']
        else:
            self._fit_trend_seasonal()

    def _fit_trend_seasonal(self):
        """Fallback: fit trend + seasonality directly if no saved params provided."""
        self.t0 = self.first_date
        t = (self.df['Dates'] - self.t0).dt.days / 365.25
        month = self.df['Dates'].dt.month
        slope, intercept = np.polyfit(t, self.df['Prices'], deg=1)
        trend_pred = slope * t + intercept
        resid = self.df['Prices'] - trend_pred
        seasonal_index = resid.groupby(month).mean()
        seasonal_index = seasonal_index - seasonal_index.mean()
        seasonal_index = seasonal_index.reindex(range(1, 13), fill_value=0)
        self.slope = slope
        self.intercept = intercept
        self.seasonal_index = seasonal_index.to_dict()
        self.residual_std = resid.std()

    def _trend_seasonal_estimate(self, date):
        """Model-based estimate: trend + seasonal index for a given date."""
        t = (date - self.t0).days / 365.25
        month = date.month
        return self.slope * t + self.intercept + self.seasonal_index[month]

    def estimate_price(self, date, return_interval=False):
        """
        Estimate gas price on a given date.

        Parameters:

        date : str or datetime-like
            The date to estimate a price for, e.g. '2024-12-15' or '3/15/25'.
        return_interval : bool
            If True, also return a rough +/- confidence range (only meaningful
            for extrapolated/future dates; historical interpolation has no
            interval since it's not a statistical estimate).

        Returns:

        float, or (float, (low, high)) if return_interval=True
        """
        date = pd.Timestamp(date)
        max_future = self.last_date + pd.DateOffset(years=1)

        if date > max_future:
            raise ValueError(
                f"Date {date.date()} is more than 1 year beyond the last known "
                f"data point ({self.last_date.date()}). Extrapolation beyond "
                f"1 year is not supported by this model."
            )

        if self.first_date <= date <= self.last_date:
            # Interpolate between known data points
            price = float(np.interp(date.toordinal(), self._x_known, self._y_known))
            interval = (price, price)  # no uncertainty for grounded interpolation
        elif date < self.first_date:
            # Before data starts: use trend+seasonal model as best-effort backcast
            price = self._trend_seasonal_estimate(date)
            years_out = (self.first_date - date).days / 365.25
            margin = 1.96 * self.residual_std * (1 + years_out)
            interval = (price - margin, price + margin)
        else:
            # Future: extrapolate using trend + seasonal
            price = self._trend_seasonal_estimate(date)
            years_out = (date - self.last_date).days / 365.25
            # Widen interval the further out we extrapolate
            margin = 1.96 * self.residual_std * (1 + years_out)
            interval = (price - margin, price + margin)

        if return_interval:
            return price, interval
        return price


