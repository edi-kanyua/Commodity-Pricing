# Convert date to a continuous numeric "time" variable (fractional years since start)
t0 = df['Dates'].min()

def date_to_t(dates):
    dates = pd.to_datetime(dates)
    delta = dates - t0
    if hasattr(delta, 'dt'):
        return delta.dt.days / 365.25
    return delta.days / 365.25

df['t'] = date_to_t(df['Dates'])
df['month'] = df['Dates'].dt.month

# TRAIN/TEST SPLIT (holdout last 6 months to validate)

HOLDOUT = 6
train = df.iloc[:-HOLDOUT].copy()
test = df.iloc[-HOLDOUT:].copy()

def fit_trend_seasonal(train_df):
    """Fit linear trend on t, then additive monthly seasonal indices on residuals."""
    # Linear trend (Price ~ a*t + b)
    coeffs = np.polyfit(train_df['t'], train_df['Prices'], deg=1)
    slope, intercept = coeffs[0], coeffs[1]

    # Residuals after removing trend
    trend_pred = slope * train_df['t'] + intercept
    resid = train_df['Prices'] - trend_pred

    # Seasonal index per calendar month = mean residual for that month
    seasonal_index = resid.groupby(train_df['month']).mean()
    # Center seasonal indices so they sum to ~0 (keeps trend line as the "mean" line)
    seasonal_index = seasonal_index - seasonal_index.mean()
    # Ensure all 12 months present (fill missing with 0 if a month never appears)
    seasonal_index = seasonal_index.reindex(range(1, 13), fill_value=0)

    return {'slope': slope, 'intercept': intercept, 'seasonal_index': seasonal_index}

model = fit_trend_seasonal(train)
print("Trend: slope =", model['slope'], "per year, intercept =", model['intercept'])
print("\nSeasonal indices (by month):")
print(model['seasonal_index'])

def predict(model, t_values, months):
    trend = model['slope'] * np.asarray(t_values) + model['intercept']
    seasonal = model['seasonal_index'].reindex(months).values
    return trend + seasonal

